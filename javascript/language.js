const root = document.documentElement;
// Storage is optional: site still works in strict/private browser modes.
function readPreference(key) { try { return localStorage.getItem(key); } catch { return null; } }
function savePreference(key, value) { try { localStorage.setItem(key, value); } catch { /* optional */ } }

const preferredLanguage = readPreference('salma-portfolio-language');

let language = Object.prototype.hasOwnProperty.call(
  TRANSLATIONS,
  preferredLanguage
) ? preferredLanguage : 'en';

function translate() {
  const t = TRANSLATIONS[language];
  root.lang = language;
  // Arabic is right-to-left; French and English remain left-to-right.
  root.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.title = t.pageTitle;
  document.querySelector('meta[name="description"]').setAttribute('content', t.pageDescription);
  const ogDescription = document.querySelector('meta[property="og:description"]');
  if (ogDescription) ogDescription.setAttribute('content', t.ogDescription);
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (!(key in t)) return;
    // All translations are plain text. Never inject translated HTML.
    node.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((node) => {
    const value = t[node.dataset.i18nAriaLabel];
    if (value) node.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((node) => {
    const value = t[node.dataset.i18nAlt];
    if (value) node.setAttribute('alt', value);
  });
  document.querySelectorAll('.language-button').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
  document.getElementById('current-language').textContent = language.toUpperCase();
  // Même drapeau dans le bouton fermé et dans l'option sélectionnée.
  const selectedLanguageFlag = document.querySelector(
    `.language-menu .language-button[data-language="${language}"] .language-flag`
  );
  const currentLanguageFlag = document.getElementById('current-language-flag');
  if (selectedLanguageFlag && currentLanguageFlag) {
    currentLanguageFlag.src = selectedLanguageFlag.getAttribute('src');
  }
  updateThemeLabel();
  updateVisionLabel();
  updateMenuLabel();
  savePreference('salma-portfolio-language', language);
}


const languageDropdown =
  document.getElementById('language-dropdown');

/* Sélection d'une langue */
document.querySelectorAll('.language-button').forEach((button) => {
  button.addEventListener('click', () => {
    language = button.dataset.language;
    translate();

    languageDropdown.open = false;
    languageDropdown.querySelector('summary').focus();
  });
});

/* Fermer le menu si on clique ailleurs */
document.addEventListener('pointerdown', (event) => {
  if (
    languageDropdown.open &&
    !languageDropdown.contains(event.target)
  ) {
    languageDropdown.open = false;
  }
});

/* Fermer avec Échap */
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && languageDropdown.open) {
    languageDropdown.open = false;
    languageDropdown.querySelector('summary').focus();
  }
});

